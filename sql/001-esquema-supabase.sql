BEGIN;

CREATE SCHEMA notioax;
REVOKE ALL ON SCHEMA notioax FROM PUBLIC, anon, authenticated;

CREATE TABLE notioax.categorias (
  id_categoria integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_categoria varchar(50) NOT NULL UNIQUE,
  color varchar(20),
  descripcion text
);

CREATE TABLE notioax.usuarios (
  id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100) NOT NULL,
  correo varchar(100) NOT NULL,
  password_hash varchar(255) NOT NULL,
  rol varchar(10) DEFAULT 'user',
  foto_perfil varchar(255),
  fecha_registro timestamp DEFAULT CURRENT_TIMESTAMP,
  estado varchar(20) DEFAULT 'activo',
  CONSTRAINT usuarios_correo_key UNIQUE (correo)
);

CREATE UNIQUE INDEX usuarios_correo_normalizado_key ON notioax.usuarios (lower(correo));

CREATE TABLE notioax.noticias (
  id_noticia integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer NOT NULL,
  id_categoria integer NOT NULL,
  titulo varchar(200) NOT NULL,
  resumen text,
  contenido text NOT NULL,
  imagen varchar(255),
  fecha date NOT NULL,
  destacada smallint DEFAULT 0,
  estado varchar(20) DEFAULT 'borrador',
  fecha_publicacion timestamp
);

CREATE INDEX noticias_id_usuario_idx ON notioax.noticias (id_usuario);
CREATE INDEX noticias_id_categoria_idx ON notioax.noticias (id_categoria);

CREATE TABLE notioax.comentarios (
  id_comentario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer NOT NULL,
  id_noticia integer NOT NULL,
  contenido text NOT NULL,
  fecha timestamp DEFAULT CURRENT_TIMESTAMP,
  estado varchar(20) DEFAULT 'visible'
);

CREATE INDEX comentarios_id_usuario_idx ON notioax.comentarios (id_usuario);
CREATE INDEX comentarios_id_noticia_idx ON notioax.comentarios (id_noticia);

ALTER TABLE notioax.categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE notioax.usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE notioax.noticias ENABLE ROW LEVEL SECURITY;
ALTER TABLE notioax.comentarios ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON ALL TABLES IN SCHEMA notioax FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA notioax FROM PUBLIC, anon, authenticated;

COMMIT;
